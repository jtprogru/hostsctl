#[test]
fn backup_and_restore_roundtrip() {
    let s = Sandbox::new();
    s.init();
    s.ok(&["add", "127.0.0.1", "one.local"]);
    s.ok(&["apply", "-y"]);
    let with_one = s.hosts();

    s.ok(&["add", "127.0.0.1", "two.local"]);
    s.ok(&["apply", "-y"]);
    assert!(s.hosts().contains("two.local"));

    let list = s.ok(&["backup", "list"]);
    assert!(list.lines().count() >= 2, "too few backups:\n{list}");

    s.ok(&["backup", "restore", "-y"]);
    assert_eq!(s.hosts(), with_one, "the restore did not bring the previous state back");
}

#[test]
fn legacy_hosts_sync_block_is_left_alone() {
    let s = Sandbox::new();
    let legacy = format!(
        "{SYSTEM_HEAD}\n# >>> hosts-sync begin >>>\n127.0.0.1 legacy.local\n# <<< hosts-sync end <<<\n"
    );
    std::fs::write(s.target(), &legacy).unwrap();
    s.init();
    s.ok(&["add", "127.0.0.1", "new.local"]);

    let out = s.run(&["apply", "-y"]);
    let stderr = String::from_utf8_lossy(&out.stderr);
    assert!(stderr.contains("hosts-sync"), "no warning:\n{stderr}");

    let hosts = s.hosts();
    assert!(hosts.contains("legacy.local"), "the legacy block was dropped without being asked");
    assert!(hosts.contains("new.local"));

    // А по явной команде — удаляется.
    s.ok(&["apply", "-y", "--drop-legacy"]);
    let hosts = s.hosts();
    assert!(!hosts.contains("hosts-sync"));
    assert!(!hosts.contains("legacy.local"));
    assert_system_lines_intact(&hosts);
}

#[test]
fn import_reads_legacy_hosts_files() {
    let s = Sandbox::new();
    s.init();
    let src = s.path("src");
    std::fs::create_dir_all(&src).unwrap();
    std::fs::write(
        src.join("10-local.hosts"),
        "# Local development\n127.0.0.1   k8s.orb.local\n# 127.0.0.1 *.k8s.orb.local\n",
    )
    .unwrap();
    std::fs::write(src.join("20-block.hosts"), "0.0.0.0 ads.example\n").unwrap();

    s.ok(&["import", src.to_str().unwrap()]);
    let list = s.ok(&["list", "--all"]);
    assert!(list.contains("k8s.orb.local"));
    assert!(list.contains("ads.example"));

    // Закомментированный wildcard импортирован выключенным и не мешает apply.
    s.ok(&["apply", "-y"]);
    let hosts = s.hosts();
    assert!(!hosts.contains('*'));
    assert!(hosts.contains("ads.example"));
}

