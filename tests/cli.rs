#[test]
fn unwritable_target_asks_for_sudo() {
    let s = Sandbox::new();
    s.init();
    s.ok(&["add", "127.0.0.1", "ro.local"]);
    let mut perms = std::fs::metadata(s.target()).unwrap().permissions();
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        perms.set_mode(0o444);
    }
    std::fs::set_permissions(s.target(), perms).unwrap();

    // root в CI сделает файл записываемым несмотря на права — тогда пропускаем.
    if unsafe { libc::geteuid() } == 0 {
        return;
    }
    let out = s.run(&["apply", "-y"]);
    assert!(!out.status.success());
    assert_eq!(out.status.code(), Some(4), "a permission failure has its own exit code");
    assert!(String::from_utf8_lossy(&out.stderr).contains("sudo"));
}

/// Коды выхода — часть контракта: скрипт должен отличать сломанный конфиг от
/// нехватки прав, не разбирая текст ошибки.
#[test]
fn exit_codes_tell_failures_apart() {
    let s = Sandbox::new();
    s.init();

    let usage = s.run(&["definitely-not-a-command"]);
    assert_eq!(usage.status.code(), Some(2), "clap reports a usage error");

    std::fs::write(s.path("config.yaml"), "version: 1\ngroups: [oops\n").unwrap();
    let broken = s.run(&["list"]);
    assert_eq!(broken.status.code(), Some(3), "an invalid config is a config error");

    let missing = Command::new(bin())
        .args(["--config", "/nonexistent/hostsctl/config.yaml", "list"])
        .env("NO_COLOR", "1")
        .output()
        .unwrap();
    assert_eq!(missing.status.code(), Some(3), "a missing config is a config error too");
}

#[test]
fn generated_docs_cover_every_command() {
    let out = Command::new(bin()).args(["docs", "cli"]).output().unwrap();
    assert!(out.status.success());
    let md = String::from_utf8_lossy(&out.stdout);
    for cmd in ["hostsctl apply", "hostsctl zone add", "hostsctl source update", "hostsctl backup"]
    {
        assert!(md.contains(&format!("`{cmd}`")), "{cmd} is missing from the reference");
    }
    // Скрытые команды в справочник не попадают: заголовка на них быть не должно.
    for hidden in ["## `hostsctl docs`", "## `hostsctl man`"] {
        assert!(!md.contains(hidden), "{hidden} should stay out of the reference");
    }

    let man = Command::new(bin()).arg("man").output().unwrap();
    assert!(man.status.success());
    let roff = String::from_utf8_lossy(&man.stdout);
    assert!(roff.contains(".TH hostsctl 1"), "the man page has no header:\n{roff}");
    assert!(roff.contains(".SH SYNOPSIS"));
}

