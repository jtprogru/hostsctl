#[test]
fn target_stays_a_regular_file_with_same_perms() {
    let s = Sandbox::new();
    s.init();
    s.ok(&["add", "127.0.0.1", "perm.local"]);
    let before = std::fs::metadata(s.target()).unwrap();
    s.ok(&["apply", "-y"]);
    let after = std::fs::metadata(s.target()).unwrap();
    #[cfg(unix)]
    {
        use std::os::unix::fs::{MetadataExt, PermissionsExt};
        assert_eq!(before.permissions().mode(), after.permissions().mode(), "the mode changed");
        assert_eq!(before.uid(), after.uid());
    }
    assert!(after.is_file());
    let _ = Path::new("/");
}
