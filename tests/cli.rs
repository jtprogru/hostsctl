#[test]
fn same_hostname_on_several_ips_is_allowed() {
    let s = Sandbox::new();
    s.init();
    s.ok(&["add", "192.178.194.100", "analytics.google.com."]);
    s.ok(&["add", "192.178.194.101", "analytics.google.com."]);
    s.ok(&["add", "192.178.194.102", "analytics.google.com."]);

    // Точный повтор пары адрес+имя — единственное, что отвергается.
    let err = s.fails(&["add", "192.178.194.100", "analytics.google.com."]);
    assert!(err.contains("is already in group"), "{err}");

    s.ok(&["apply", "-y"]);
    let hosts = s.hosts();
    for ip in ["192.178.194.100", "192.178.194.101", "192.178.194.102"] {
        assert!(hosts.contains(ip), "lost address {ip}:\n{hosts}");
    }
    assert_eq!(
        hosts.matches("analytics.google.com.").count(),
        3,
        "there should be three lines:\n{hosts}"
    );

    // Удаление по IP снимает только его.
    s.ok(&["rm", "192.178.194.101", "--apply"]);
    let hosts = s.hosts();
    assert!(!hosts.contains("192.178.194.101"));
    assert!(hosts.contains("192.178.194.100") && hosts.contains("192.178.194.102"));

    // А по имени — все его адреса разом.
    s.ok(&["rm", "analytics.google.com.", "--apply"]);
    assert!(!s.hosts().contains("192.178.194.100"));
}

#[test]
fn one_ip_keeps_many_hostnames() {
    let s = Sandbox::new();
    s.init();
    s.ok(&["add", "10.0.0.7", "a.local", "b.local", "c.local"]);
    s.ok(&["apply", "-y"]);
    let hosts = s.hosts();
    assert!(
        hosts.lines().any(|l| l.starts_with("10.0.0.7") && l.ends_with("a.local b.local c.local")),
        "{hosts}"
    );

    s.ok(&["rm", "b.local", "--apply"]);
    let hosts = s.hosts();
    assert!(hosts.contains("a.local c.local"));
    assert!(!hosts.contains("b.local"));
}

