//! Прогон настоящего бинарника по временному «/etc/hosts».
//!
//! Проверяем главное обещание утилиты: всё, что вне маркеров, остаётся на месте.

mod common;
use common::{SYSTEM_HEAD, Sandbox, assert_system_lines_intact, bin};
