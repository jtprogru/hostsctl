use std::process::Command;

#[test]
fn full_lifecycle_keeps_system_lines() {
    let s = Sandbox::new();
    s.init();

    s.ok(&["add", "127.0.0.1", "k8s.orb.local", "--comment", "orbstack"]);
    s.ok(&["add", "10.30.13.37", "sre-mcp.local"]);
    s.ok(&["apply", "-y"]);

    let hosts = s.hosts();
    assert_system_lines_intact(&hosts);
    assert!(hosts.contains("k8s.orb.local"));
    assert!(hosts.contains("sre-mcp.local"));
    assert!(hosts.contains("# >>> hostsctl begin >>>"));

    // Повторный apply идемпотентен по содержимому блока.
    s.ok(&["apply", "-y"]);
    let again = s.hosts();
    assert_eq!(again.matches("# >>> hostsctl begin >>>").count(), 1, "the block was duplicated");

    // disable убирает запись из файла, но не из конфига
    s.ok(&["disable", "sre-mcp.local"]);
    s.ok(&["apply", "-y"]);
    let hosts = s.hosts();
    assert!(!hosts.contains("sre-mcp.local"));
    assert!(s.ok(&["list", "--all"]).contains("sre-mcp.local"));
    assert_system_lines_intact(&hosts);

    // off убирает блок целиком, файл возвращается к исходному виду
    s.ok(&["off", "-y"]);
    let hosts = s.hosts();
    assert!(!hosts.contains("hostsctl begin"));
    assert!(!hosts.contains("k8s.orb.local"));
    assert_system_lines_intact(&hosts);
}

#[test]
fn manual_edits_outside_block_survive_apply() {
    let s = Sandbox::new();
    s.init();
    s.ok(&["add", "127.0.0.1", "app.local"]);
    s.ok(&["apply", "-y"]);

    // Пользователь дописал строку руками уже после apply.
    let mut hosts = s.hosts();
    hosts.push_str("\n# added by hand\n192.168.1.10 printer.home\n");
    std::fs::write(s.target(), &hosts).unwrap();

    s.ok(&["add", "127.0.0.1", "api.local"]);
    s.ok(&["apply", "-y"]);

    let after = s.hosts();
    assert!(after.contains("192.168.1.10 printer.home"));
    assert!(after.contains("# added by hand"));
    assert!(after.contains("api.local"));
    assert_system_lines_intact(&after);
}

#[test]
fn stale_timestamp_alone_is_not_drift() {
    let s = Sandbox::new();
    s.init();
    s.ok(&["add", "127.0.0.1", "stable.local"]);
    s.ok(&["apply", "-y"]);

    // Отматываем отметку времени назад — как будто apply был вчера.
    let hosts = s.hosts();
    let old = hosts
        .lines()
        .map(|l| {
            if l.starts_with("# generated by hostsctl ") {
                "# generated by hostsctl 2020-01-01 00:00".to_string()
            } else {
                l.to_string()
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
        + "\n";
    std::fs::write(s.target(), &old).unwrap();

    assert!(s.ok(&["diff"]).contains("no changes"), "diff sees drift that is not there");
    assert!(s.ok(&["status"]).contains("matches the config"));
    s.ok(&["apply", "-y"]);
    assert_eq!(s.hosts(), old, "apply rewrote the file for no reason");

    // А настоящее изменение отметку обновляет.
    s.ok(&["add", "127.0.0.1", "fresh.local", "--apply"]);
    assert!(!s.hosts().contains("2020-01-01"));
}

